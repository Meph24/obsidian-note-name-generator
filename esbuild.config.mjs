import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";

const prod = process.argv[2] === "production";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source: https://gitlab.com/Meph24/obsidian-note-name-generator
*/
`;

// Default: bundle into the repo root (what gets released).
// Set OBSIDIAN_PLUGINS_DIR=<vault>/.obsidian/plugins to build straight into the vault during development.
const pluginsDir = process.env.OBSIDIAN_PLUGINS_DIR;
const outfile = pluginsDir ? `${pluginsDir}/note-name-generator/main.js` : "main.js";

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		...builtinModules,
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile,
	minify: false,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
